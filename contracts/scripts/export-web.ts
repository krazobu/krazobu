/**
 * Copies contract ABIs and Ignition deployment addresses into the web app.
 * Run after `hardhat build` / `hardhat ignition deploy`:  node scripts/export-web.ts
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "..", "web", "src", "contracts");
mkdirSync(outDir, { recursive: true });

const artifacts: Array<[exportName: string, artifactPath: string]> = [
  ["shinkanshenFarmAbi", "contracts/ShinkanshenFarm.sol/ShinkanshenFarm.json"],
  ["shinkanshenTokenAbi", "contracts/ShinkanshenToken.sol/ShinkanshenToken.json"],
  ["mockBep20Abi", "contracts/mocks/MockBEP20.sol/MockBEP20.json"],
];

let abis = "// Generated by contracts/scripts/export-web.ts — do not edit by hand.\n";
for (const [name, path] of artifacts) {
  const file = join(root, "artifacts", path);
  if (!existsSync(file)) throw new Error(`Missing artifact ${file}. Run \`hardhat build\` first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  abis += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(join(outDir, "abis.ts"), abis);

const deploymentsFile = join(outDir, "deployments.json");
const deployments: Record<string, { token: string; farm: string }> = existsSync(deploymentsFile)
  ? JSON.parse(readFileSync(deploymentsFile, "utf8"))
  : {};

const deploymentsDir = join(root, "ignition", "deployments");
if (existsSync(deploymentsDir)) {
  for (const entry of readdirSync(deploymentsDir)) {
    const match = /^chain-(\d+)$/.exec(entry);
    const addressesFile = join(deploymentsDir, entry, "deployed_addresses.json");
    if (!match || !existsSync(addressesFile)) continue;
    const addresses: Record<string, string> = JSON.parse(readFileSync(addressesFile, "utf8"));
    const find = (contract: string) =>
      Object.entries(addresses).find(([key]) => key.endsWith(`#${contract}`))?.[1];
    const token = find("ShinkanshenToken");
    const farm = find("ShinkanshenFarm");
    if (token && farm) deployments[match[1]] = { token, farm };
  }
}
writeFileSync(deploymentsFile, `${JSON.stringify(deployments, null, 2)}\n`);

console.log(`Exported ${artifacts.length} ABIs and deployments for chains [${Object.keys(deployments).join(", ")}] to ${outDir}`);
